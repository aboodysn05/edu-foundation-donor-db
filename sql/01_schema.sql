CREATE DATABASE EDU_FOUNDATION;
USE EDU_FOUNDATION;

CREATE TABLE DONOR (
    DonorID INT PRIMARY KEY,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    City VARCHAR(50) NOT NULL,
    Street VARCHAR(50) NOT NULL,
    Building INT,
    Career VARCHAR(50),
    FirstDonationDate DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DONOR_PHONE (
    DonorID INT,
    Phone VARCHAR(15) UNIQUE NOT NULL,
    PRIMARY KEY (DonorID, Phone),
    FOREIGN KEY (DonorID) REFERENCES DONOR(DonorID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE DONOR_EMAIL (
    DonorID INT,
    Email VARCHAR(100) UNIQUE NOT NULL CHECK (Email LIKE '%@%'),
    PRIMARY KEY (DonorID, Email),
    FOREIGN KEY (DonorID) REFERENCES DONOR(DonorID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE Department (
    DepartmentID INT PRIMARY KEY,
    DepartmentName VARCHAR(100) NOT NULL,
    Description VARCHAR(255),
    Email VARCHAR(100) UNIQUE NOT NULL CHECK (Email LIKE '%@%')
);

CREATE TABLE Employee (
    EmployeeID INT PRIMARY KEY,
    FirstName VARCHAR(50) NOT NULL,
    LastName VARCHAR(50) NOT NULL,
    Role VARCHAR(50) NOT NULL,
    Email VARCHAR(100) UNIQUE NOT NULL CHECK (Email LIKE '%@%'),
    DepartmentID INT,
    FOREIGN KEY (DepartmentID) REFERENCES Department(DepartmentID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE Event (
    EventID INT PRIMARY KEY,
    EventName VARCHAR(100) NOT NULL,
    EventDate DATE NOT NULL,
    City VARCHAR(50) NOT NULL,
    Street VARCHAR(50) NOT NULL,
    Building INT,
    Description VARCHAR(255),
    EmployeeID INT,
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE Sponsorship (
    SponsorshipID INT PRIMARY KEY,
    SponsorName VARCHAR(100) NOT NULL,
    Amount DOUBLE NOT NULL CHECK (Amount > 0),
    SponsorshipDate DATE,
    EventID INT,
    FOREIGN KEY (EventID) REFERENCES Event(EventID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE Donation (
    DonationID INT PRIMARY KEY,
    DonationDate DATETIME DEFAULT CURRENT_TIMESTAMP,
    Amount DOUBLE NOT NULL CHECK (Amount > 0),
    Purpose VARCHAR(255) DEFAULT "Helping People",
    DonorID INT,
    FOREIGN KEY (DonorID) REFERENCES DONOR(DonorID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE EventParticipants (
    EventID INT,
    DonorID INT,
    PRIMARY KEY (EventID, DonorID),
    FOREIGN KEY (EventID) REFERENCES Event(EventID)
	ON DELETE CASCADE
	ON UPDATE CASCADE,
    FOREIGN KEY (DonorID) REFERENCES DONOR(DonorID)
	ON DELETE CASCADE
	ON UPDATE CASCADE
);

CREATE TABLE CommunicationTable (
    DonorID INT,
    EmployeeID INT,
    CommunicationDate DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (DonorID, EmployeeID),
    FOREIGN KEY (DonorID) REFERENCES DONOR(DonorID)
	ON DELETE CASCADE
	ON UPDATE CASCADE,
    FOREIGN KEY (EmployeeID) REFERENCES Employee(EmployeeID) 
	ON DELETE CASCADE
	ON UPDATE CASCADE
);
